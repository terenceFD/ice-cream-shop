export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try {
      const savedLanguage = localStorage.getItem(LANGUAGE_STORAGE_KEY)
      if (savedLanguage === 'en' || savedLanguage === 'fr') return savedLanguage
    } catch (error) {
      console.error('Unable to read the saved language preference.', error)
    }
    return navigator.languages?.some((value) => value.toLowerCase().startsWith('fr'))
      || navigator.language?.toLowerCase().startsWith('fr')
      ? 'fr'
      : 'en'
  })

  useEffect(() => {
    document.documentElement.lang = language
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, language)
    } catch (error) {
      console.error('Unable to save the language preference.', error)
    }
  }, [language])

  const value = useMemo(() => ({
    language,
    setLanguage,
    t(key, variables = {}) {
      let result = language === 'fr' ? french[key] || key : key
      for (const [name, replacement] of Object.entries(variables)) {
        result = result.replaceAll(`{${name}}`, String(replacement))
      }
      return result
    },
  }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used within LanguageProvider')
  return context
}
